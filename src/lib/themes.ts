export interface ThemeVars {
  "--background": string;
  "--foreground": string;
  "--card": string;
  "--card-foreground": string;
  "--popover": string;
  "--popover-foreground": string;
  "--primary": string;
  "--primary-foreground": string;
  "--secondary": string;
  "--secondary-foreground": string;
  "--muted": string;
  "--muted-foreground": string;
  "--accent": string;
  "--accent-foreground": string;
  "--destructive": string;
  "--destructive-foreground": string;
  "--border": string;
  "--input": string;
  "--ring": string;
  "--zt-sub": string;
  "--chart-1": string;
  "--chart-2": string;
  "--chart-3": string;
  "--chart-4": string;
  "--chart-5": string;
}

export interface ThemePalette {
  id: string;
  label: string;
  appearance: "dark" | "light";
  vars: ThemeVars;
}

function theme(
  id: string,
  label: string,
  appearance: "dark" | "light",
  v: Omit<ThemeVars, "--card-foreground" | "--popover-foreground" | "--destructive-foreground"> &
    Partial<Pick<ThemeVars, "--card-foreground" | "--popover-foreground" | "--destructive-foreground">>,
): ThemePalette {
  return {
    id,
    label,
    appearance,
    vars: {
      ...v,
      "--card-foreground": v["--card-foreground"] ?? v["--foreground"],
      "--popover-foreground": v["--popover-foreground"] ?? v["--foreground"],
      "--destructive-foreground": v["--destructive-foreground"] ?? v["--background"],
    } as ThemeVars,
  };
}

